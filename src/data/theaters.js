export function getSavedCity() {
  try {
    const saved = localStorage.getItem('reelist_user_city');
    if (saved && CITY_THEATERS[saved]) {
      return saved;
    }
  } catch (e) {}
  return 'kallakurichi'; // Defaults to user hometown!
}

export function saveCity(cityId) {
  try {
    if (CITY_THEATERS[cityId]) {
      localStorage.setItem('reelist_user_city', cityId);
    }
  } catch (e) {}
}

export function getCityDetails(cityId) {
  return TAMIL_NADU_CITIES.find((c) => c.id === cityId) || TAMIL_NADU_CITIES[0];
}

export function getTheatersForCity(cityId) {
  return CITY_THEATERS[cityId] || CITY_THEATERS['kallakurichi'];
}
